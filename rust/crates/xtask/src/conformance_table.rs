//! `conformance-table`: renders the parser conformance table into docs/indexing.md.

use std::collections::BTreeSet;
use std::fs;
use std::process::ExitCode;

use serde_json::Value;

use crate::check_doc_links::repo_root;

const BEGIN: &str = "<!-- conformance:begin (generated by scripts/gen_conformance_table.py) -->";
const END: &str = "<!-- conformance:end -->";
const MARKERS_MISSING: &str = "conformance markers missing from docs/indexing.md";

fn languages(golden: &std::path::Path) -> Vec<String> {
    let mut langs: Vec<String> = fs::read_dir(golden)
        .map(|rd| {
            rd.filter_map(Result::ok)
                .filter(|e| e.path().join("expected.json").is_file())
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    langs.sort();
    langs
}

fn len_of(value: &Value, key: &str) -> usize {
    value.get(key).and_then(Value::as_array).map_or(0, Vec::len)
}

fn row(golden: &std::path::Path, lang: &str) -> Result<String, String> {
    let path = golden.join(lang).join("expected.json");
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let expected: Value =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
    let kinds: BTreeSet<&str> = expected["edges"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|e| e["kind"].as_str())
        .collect();
    let calls = kinds.contains("calls");
    let hierarchy = kinds.contains("extends") || kinds.contains("implements");
    let imports = len_of(&expected, "imports");
    let mut tiers = Vec::new();
    if imports == 0 {
        tiers.push("no import edges");
    }
    if !hierarchy {
        tiers.push("no hierarchy edges");
    }
    if !calls {
        tiers.push("symbols only");
    }
    let tier = if tiers.is_empty() {
        "green".to_string()
    } else {
        tiers.join("; ")
    };
    Ok(format!(
        "| {lang} | green | {} | {} | {imports} | {tier} |",
        len_of(&expected, "symbols"),
        len_of(&expected, "edges"),
    ))
}

pub(crate) fn render_table(golden: &std::path::Path) -> Result<(String, usize), String> {
    let langs = languages(golden);
    let mut lines = vec![
        "| Language | Golden | Symbols | Edges | Imports | Status |".to_string(),
        "|---|---|---|---|---|---|".to_string(),
    ];
    for lang in &langs {
        lines.push(row(golden, lang)?);
    }
    Ok((lines.join("\n"), langs.len()))
}

fn execute(check: bool) -> Result<(String, bool), String> {
    let root = repo_root();
    let (table, rows) = render_table(&root.join("tests/fixtures/golden"))?;
    let doc = root.join("docs/indexing.md");
    let text = fs::read_to_string(&doc).map_err(|e| format!("{}: {e}", doc.display()))?;
    if check {
        let (Some(start), Some(end)) = (text.find(BEGIN), text.find(END)) else {
            return Ok((MARKERS_MISSING.into(), false));
        };
        let committed = text.get(start + BEGIN.len()..end).unwrap_or("").trim();
        if committed != table {
            return Ok((
                "committed conformance table is stale; regenerate with scripts/gen_conformance_table.py"
                    .into(),
                false,
            ));
        }
        return Ok((format!("conformance table fresh ({rows} rows)"), true));
    }
    let Some((head, rest)) = text.split_once(BEGIN) else {
        return Ok((MARKERS_MISSING.into(), false));
    };
    let Some((_, tail)) = rest.split_once(END) else {
        return Ok((MARKERS_MISSING.into(), false));
    };
    fs::write(&doc, format!("{head}{BEGIN}\n\n{table}\n\n{END}{tail}"))
        .map_err(|e| format!("{}: {e}", doc.display()))?;
    Ok((format!("wrote {rows} rows to docs/indexing.md"), true))
}

pub fn run(args: &[String]) -> ExitCode {
    match execute(args.iter().any(|a| a == "--check")) {
        Ok((message, ok)) => {
            println!("{message}");
            if ok {
                ExitCode::SUCCESS
            } else {
                ExitCode::FAILURE
            }
        }
        Err(e) => {
            eprintln!("xtask conformance-table: {e}");
            ExitCode::FAILURE
        }
    }
}

