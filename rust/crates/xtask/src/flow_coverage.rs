//! `flow-coverage`: regenerate docs/flows/coverage.md from tests matching docs/flows/flows.json.

use std::fs;
use std::process::ExitCode;
use std::sync::LazyLock;

use regex::Regex;
use serde::Deserialize;
use walkdir::WalkDir;

use crate::check_doc_links::repo_root;

const COVERAGE_MD: &str = "docs/flows/coverage.md";
const FLOWS_JSON: &str = "docs/flows/flows.json";

static FLOW_TAG: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"//\s*F(\d+)\b").unwrap());

#[derive(Deserialize)]
pub(crate) struct FlowSpec {
    pub(crate) id: String,
    pub(crate) name: String,
    #[serde(default)]
    pub(crate) patterns: Vec<String>,
}

#[derive(Deserialize)]
struct Registry {
    flows: Vec<FlowSpec>,
}

pub(crate) struct FlowHits {
    pub(crate) spec: FlowSpec,
    pub(crate) files: Vec<String>,
}

/// Lists test files that matched no flow — a new flow missing from flows.json, or a misnamed test.
pub(crate) fn unclassified_files(hits: &[FlowHits], paths: &[String]) -> Vec<String> {
    paths
        .iter()
        .filter(|p| !hits.iter().any(|h| h.files.contains(p)))
        .cloned()
        .collect()
}

fn flow_matches(spec: &FlowSpec, rel_path: &str, content: &str) -> bool {
    spec.patterns
        .iter()
        .any(|p| rel_path.contains(p) || content.contains(p))
        || content.lines().any(|line| {
            FLOW_TAG
                .captures(line)
                .is_some_and(|c| c[1] == spec.id[1..])
        })
}

pub(crate) fn count_flows<I>(flows: Vec<FlowSpec>, files: I) -> Vec<FlowHits>
where
    I: IntoIterator<Item = (String, String)>,
{
    let files: Vec<(String, String)> = files.into_iter().collect();
    flows
        .into_iter()
        .map(|spec| {
            let mut matched = files
                .iter()
                .filter(|(path, content)| flow_matches(&spec, path, content))
                .map(|(path, _)| path.clone())
                .collect::<Vec<_>>();
            matched.sort();
            FlowHits {
                spec,
                files: matched,
            }
        })
        .collect()
}

fn render(hits: &[FlowHits]) -> String {
    let mut ordered: Vec<&FlowHits> = hits.iter().collect();
    ordered.sort_by(|a, b| {
        b.files
            .len()
            .cmp(&a.files.len())
            .then(a.spec.id.cmp(&b.spec.id))
    });
    let mut out = String::new();
    out.push_str("# Flow test coverage\n\n");
    out.push_str("Generated by `cargo xtask flow-coverage` — do not edit by hand.\n");
    out.push_str("Counting basis: integration/golden test files under `rust/crates/**/tests/`\n");
    out.push_str(
        "whose path or content matches the flow's patterns in [flows.json](flows.json),\n",
    );
    out.push_str("plus explicit `// F#` tags. Inline `#[cfg(test)]` modules are not counted.\n\n");
    out.push_str("| Flow | Test files | Matching test files |\n| --- | --- | --- |\n");
    for hit in ordered {
        let names: Vec<String> = hit
            .files
            .iter()
            .map(|p| {
                p.rsplit('/')
                    .take(2)
                    .collect::<Vec<_>>()
                    .into_iter()
                    .rev()
                    .collect::<Vec<_>>()
                    .join("/")
            })
            .collect();
        out.push_str(&format!(
            "| {} {} | {} | {} |\n",
            hit.spec.id,
            hit.spec.name,
            hit.files.len(),
            if names.is_empty() {
                "—".to_string()
            } else {
                names.join(", ")
            }
        ));
    }
    out
}

fn integration_test_files(root: &std::path::Path) -> Vec<(String, String)> {
    let crates = root.join("rust").join("crates");
    WalkDir::new(&crates)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|e| e.file_type().is_file())
        .filter(|e| {
            e.path().extension().is_some_and(|x| x == "rs")
                && e.path().components().any(|c| c.as_os_str() == "tests")
                && !e.path().components().any(|c| c.as_os_str() == "common")
        })
        .map(|e| {
            let rel = e
                .path()
                .strip_prefix(root)
                .unwrap_or(e.path())
                .to_string_lossy()
                .into_owned();
            let content = fs::read_to_string(e.path()).unwrap_or_default();
            (rel, content)
        })
        .collect()
}

pub(crate) fn run(args: &[String]) -> ExitCode {
    let check = args.iter().any(|a| a == "--check");
    let root = repo_root();
    let registry_path = root.join(FLOWS_JSON);
    let Ok(registry_raw) = fs::read_to_string(&registry_path) else {
        eprintln!("cannot read {}", FLOWS_JSON);
        return ExitCode::FAILURE;
    };
    let registry: Registry = match serde_json::from_str(&registry_raw) {
        Ok(r) => r,
        Err(e) => {
            eprintln!("{}: {e}", FLOWS_JSON);
            return ExitCode::FAILURE;
        }
    };
    let files = integration_test_files(&root);
    let paths: Vec<String> = files.iter().map(|(p, _)| p.clone()).collect();
    let hits = count_flows(registry.flows, files);
    let orphans = {
        let mut o = unclassified_files(&hits, &paths);
        o.sort();
        o
    };
    if !orphans.is_empty() {
        eprintln!(
            "warning: {} test file(s) match no flow in {}; new flow or misnamed test?",
            orphans.len(),
            FLOWS_JSON
        );
        for path in &orphans {
            eprintln!("  {path}");
        }
    }
    let rendered = render(&hits);
    if check {
        match fs::read_to_string(root.join(COVERAGE_MD)) {
            Ok(current) if current == rendered => ExitCode::SUCCESS,
            _ => {
                eprintln!("{COVERAGE_MD} is stale; run `cargo xtask flow-coverage` and commit");
                ExitCode::FAILURE
            }
        }
    } else {
        if let Err(e) = fs::write(root.join(COVERAGE_MD), &rendered) {
            eprintln!("cannot write {COVERAGE_MD}: {e}");
            return ExitCode::FAILURE;
        }
        for hit in &hits {
            println!("{:>2}  {} {}", hit.files.len(), hit.spec.id, hit.spec.name);
        }
        ExitCode::SUCCESS
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn flows() -> Vec<FlowSpec> {
        vec![
            FlowSpec {
                id: "F1".into(),
                name: "build".into(),
                patterns: vec!["builder".into(), "watcher_service".into()],
            },
            FlowSpec {
                id: "F7".into(),
                name: "federation".into(),
                patterns: vec!["federated_search".into()],
            },
        ]
    }

    #[test]
    fn counts_distinct_files_per_flow_across_path_and_content() {
        let files = vec![
            (
                "rust/crates/cairn-build/tests/builder_parity.rs".into(),
                "fn t() {}".into(),
            ),
            (
                "rust/crates/cairn-build/tests/incr.rs".into(),
                "use builder_x;".into(),
            ),
            (
                "rust/crates/cairn-query/tests/nav.rs".into(),
                "federated_search_text();".into(),
            ),
            (
                "rust/crates/cairn-build/tests/watcher_service.rs".into(),
                String::new(),
            ),
        ];
        let hits = count_flows(flows(), files);
        let f1 = hits.iter().find(|h| h.spec.id == "F1").unwrap();
        let f7 = hits.iter().find(|h| h.spec.id == "F7").unwrap();
        assert_eq!(f1.files.len(), 3);
        assert_eq!(f7.files.len(), 1);
    }

    #[test]
    fn flow_tag_credits_a_flow_without_patterns() {
        let files = vec![(
            "rust/crates/cairn-query/tests/federation_cli.rs".into(),
            "// F7\nfn t() {}".into(),
        )];
        let hits = count_flows(flows(), files);
        let f7 = hits.iter().find(|h| h.spec.id == "F7").unwrap();
        assert_eq!(f7.files.len(), 1);
    }

    #[test]
    fn no_matches_yields_zero_files() {
        let hits = count_flows(
            flows(),
            vec![("rust/crates/x/tests/a.rs".into(), "fn t() {}".into())],
        );
        assert!(hits.iter().all(|h| h.files.is_empty()));
    }

    #[test]
    fn unclassified_files_flags_tests_matching_no_flow() {
        let files: Vec<(String, String)> = vec![
            (
                "rust/crates/cairn-build/tests/builder_parity.rs".into(),
                "use builder;".into(),
            ),
            ("rust/crates/x/tests/orphan.rs".into(), "fn t() {}".into()),
        ];
        let paths: Vec<String> = files.iter().map(|f| f.0.clone()).collect();
        let hits = count_flows(flows(), files);
        assert_eq!(
            unclassified_files(&hits, &paths),
            vec!["rust/crates/x/tests/orphan.rs".to_string()]
        );
    }

    #[test]
    fn matched_file_lists_are_sorted_regardless_of_input_order() {
        let mk = |p: &str| (p.to_string(), "use builder;".to_string());
        let hits = count_flows(
            flows(),
            vec![
                mk("rust/crates/b/tests/b.rs"),
                mk("rust/crates/a/tests/a.rs"),
            ],
        );
        let f1 = hits.iter().find(|h| h.spec.id == "F1").unwrap();
        assert_eq!(
            f1.files,
            vec![
                "rust/crates/a/tests/a.rs".to_string(),
                "rust/crates/b/tests/b.rs".to_string()
            ]
        );
    }
}
