fn read_cases_payload() -> Result<Value, Halt> {
    let path = cases_file();
    if !path.is_file() {
        return Err(format!(
            "missing frozen cases {}; the fixtures are frozen — restore them from history",
            path.display()
        )
        .into());
    }
    serde_json::from_str(&read_text(&path)?)
        .map_err(|err| format!("parse {}: {err}", path.display()).into())
}

fn load_cases() -> Result<Vec<Value>, Halt> {
    let data = read_cases_payload()?;
    match data.get("schema") {
        Some(Value::String(schema)) if schema == SCHEMA => {}
        other => {
            let found = match other {
                None => "None".to_string(),
                Some(Value::String(text)) => gr::py_str_repr(text),
                Some(value) => value.to_string(),
            };
            return Err(format!(
                "{}: schema {found} != {}",
                cases_file().display(),
                gr::py_str_repr(SCHEMA)
            )
            .into());
        }
    }
    Ok(data["cases"].as_array().cloned().unwrap_or_default())
}

fn label_of(case: &Value) -> &str {
    case["label"].as_str().unwrap_or_default()
}

/// `json.dumps(value, indent=1, ensure_ascii=False)`.
fn py_json_indent1(value: &Value) -> String {
    let mut buf = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b" ");
    let mut ser = serde_json::Serializer::with_formatter(&mut buf, formatter);
    let _ = value.serialize(&mut ser);
    String::from_utf8(buf).unwrap_or_default()
}

/// `datetime.now(timezone.utc).isoformat()`.
fn utc_now_iso() -> String {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default();
    let secs = now.as_secs();
    let days = i64::try_from(secs / 86_400).unwrap_or_default();
    let rem = secs % 86_400;
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    let micros = now.subsec_micros();
    let frac = if micros == 0 {
        String::new()
    } else {
        format!(".{micros:06}")
    };
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}{frac}+00:00",
        rem / 3600,
        rem % 3600 / 60,
        rem % 60
    )
}

/// The recorded executable, repo-relative when it lives in the checkout.
fn reference_label(exe: &Path) -> String {
    let real = gr::realpath(exe);
    match real.strip_prefix(repo_root()) {
        Ok(rel) => rel.to_string_lossy().into_owned(),
        Err(_) => exe.to_string_lossy().into_owned(),
    }
}

/// Capture every case into the frozen cases file; `only` re-freezes the label-prefixed cases.
fn record(
    commands: &[Vec<String>],
    exe: &Path,
    env: &Env,
    scratch: &Path,
    rules: &[ScrubRule],
    only: Option<&str>,
) -> Result<(), Halt> {
    let frozen: BTreeMap<String, Value> = match only {
        Some(_) => load_cases()?
            .into_iter()
            .map(|case| (label_of(&case).to_string(), case))
            .collect(),
        None => BTreeMap::new(),
    };
    let (mut cases, mut refreshed) = (Vec::new(), Vec::new());
    for cmd in commands {
        let label = case_label(cmd, rules);
        if let Some(prefix) = only.filter(|prefix| !label.starts_with(prefix)) {
            let case = frozen.get(&label).cloned().ok_or_else(|| {
                format!(
                    "no frozen case {} to keep outside --only {}",
                    gr::py_str_repr(&label),
                    gr::py_str_repr(prefix)
                )
            })?;
            cases.push(case);
            continue;
        }
        let out = run_case(cmd, exe, env, scratch)?;
        cases.push(json!({
            "label": label,
            "exit": out.code,
            "stdout": normalize(&out.stdout, rules),
            "stderr": normalize(&out.stderr, rules),
        }));
        println!("RECORDED {label} (exit {})", out.code);
        refreshed.push(label);
    }
    let reference = reference_label(exe);
    let captured_at = utc_now_iso();
    let capture = if only.is_some() {
        let mut previous = read_cases_payload()?["capture"]
            .as_object()
            .cloned()
            .unwrap_or_default();
        let mut stamps = previous
            .get("refreshed")
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        for label in refreshed {
            stamps.insert(
                label,
                json!({"reference": reference, "captured_at": captured_at}),
            );
        }
        previous.insert("refreshed".to_string(), Value::Object(stamps));
        Value::Object(previous)
    } else {
        let pins: Map<String, Value> = gr::ENV_PINS
            .iter()
            .map(|(key, value)| ((*key).to_string(), json!(value)))
            .collect();
        json!({"reference": reference, "captured_at": captured_at, "env_pins": pins})
    };
    let payload = json!({
        "schema": SCHEMA,
        "capture": capture,
        "normalization": rules.iter().map(|rule| rule.name.clone()).collect::<Vec<_>>(),
        "cases": cases,
    });
    mkdirs(&fixture_dir())?;
    let path = cases_file();
    write_text(&path, &format!("{}\n", py_json_indent1(&payload)))?;
    note(&format!(
        "recorded {} cases into {}",
        cases.len(),
        path.display()
    ));
    Ok(())
}

/// Run every case and diff it against the frozen fixture; 0 when all are golden-equal.
fn replay(
    commands: &[Vec<String>],
    exe: &Path,
    env: &Env,
    scratch: &Path,
    rules: &[ScrubRule],
) -> Result<u8, Halt> {
    let cases = load_cases()?;
    let labels: Vec<String> = commands.iter().map(|cmd| case_label(cmd, rules)).collect();
    let frozen: Vec<&str> = cases.iter().map(label_of).collect();
    if labels != frozen {
        if let Some((i, (live, want))) = labels
            .iter()
            .zip(&frozen)
            .enumerate()
            .find(|(_, (live, want))| live != *want)
        {
            return Err(format!(
                "case {i}: live {} != frozen {}; re-record the fixtures",
                gr::py_str_repr(live),
                gr::py_str_repr(want)
            )
            .into());
        }
        return Err(format!(
            "{} live cases vs {} frozen; re-record the fixtures",
            labels.len(),
            frozen.len()
        )
        .into());
    }
    let mut failures = 0;
    for (cmd, case) in commands.iter().zip(&cases) {
        let outcome = run_case(cmd, exe, env, scratch)?;
        match first_diff(case, &outcome, rules)? {
            Some(diff) => {
                failures += 1;
                println!("FAIL {}: {}", label_of(case), parity::shrink(&diff));
            }
            None => println!("PASS {}", label_of(case)),
        }
    }
    let total = commands.len();
    println!("{}/{total} commands golden-equal", total - failures);
    Ok(u8::from(failures > 0))
}

// --- entry point --------------------------------------------------------------------

#[derive(Parser)]
#[command(
    name = "cli-golden",
    about = "C-4 CLI golden gate: replay the fixed machine-contract command set against the frozen fixtures under rust/golden/cli."
)]
struct Args {
    /// Rust binary override (default: build rust/target/release/cairn).
    #[arg(long)]
    rust_bin: Option<PathBuf>,
    /// Re-freeze the fixtures from the rust binary instead of replaying against them.
    #[arg(long)]
    record: bool,
    /// With --record: re-freeze only the cases whose label starts with LABEL, keeping the rest.
    #[arg(long, value_name = "LABEL")]
    only: Option<String>,
    /// Keep the scratch store for inspection.
    #[arg(long)]
    keep_scratch: bool,
}

fn golden(args: &Args, scratch: &Path) -> Result<u8, Halt> {
    let workspace = scratch.join("corpus");
    prepare_store(scratch)?;
    let mut rules = gr::scrub_rules(scratch, &scratch.join("home"), &workspace);
    rules.extend(extra_scrub_rules());
    let commands = golden_commands(scratch)?;
    let exe = match &args.rust_bin {
        Some(bin) => gr::realpath(bin),
        None => ensure_rust_binary()?,
    };
    let env = cli_env(scratch, &workspace)?;
    note(&format!("binary: {}", exe.display()));
    if args.record {
        let only = args.only.as_deref().filter(|prefix| !prefix.is_empty());
        record(&commands, &exe, &env, scratch, &rules, only)?;
        return Ok(0);
    }
    replay(&commands, &exe, &env, scratch, &rules)
}

pub fn run(args: &[String]) -> ExitCode {
    let args = match Args::try_parse_from(
        std::iter::once("cli-golden".to_string()).chain(args.iter().cloned()),
    ) {
        Ok(args) => args,
        Err(err) => {
            let _ = err.print();
            return ExitCode::from(u8::try_from(err.exit_code()).unwrap_or(2));
        }
    };
    let scratch = match parity::make_scratch("cairn-rust-cli-golden-") {
        Ok(scratch) => scratch,
        Err(halt) => return parity::exit_code(Err(halt)),
    };
    note(&format!("scratch {}", scratch.display()));
    let result = golden(&args, &scratch);
    if args.keep_scratch {
        note(&format!("scratch kept: {}", scratch.display()));
    } else {
        remove_tree(&scratch);
    }
    parity::exit_code(result)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn record_serializer_reproduces_the_frozen_cases_file() {
        let text = fs::read_to_string(cases_file()).unwrap_or_else(|err| panic!("{err}"));
        let payload: Value = serde_json::from_str(&text).unwrap_or_else(|err| panic!("{err}"));
        assert_eq!(format!("{}\n", py_json_indent1(&payload)), text);
    }

    #[test]
    fn replay_of_the_cli_goldens_is_golden_equal() {
        let bin = parity::target_dir().join("release").join("cairn");
        if !bin.exists() {
            parity::require_release_artifact(&bin);
            return;
        }
        let args = Args {
            rust_bin: None,
            record: false,
            only: None,
            keep_scratch: false,
        };
        let scratch = parity::make_scratch("cairn-rust-cli-golden-test-")
            .unwrap_or_else(|_| panic!("scratch"));
        let result = golden(&args, &scratch);
        remove_tree(&scratch);
        assert!(matches!(result, Ok(0)), "cli goldens are not golden-equal");
    }
}
