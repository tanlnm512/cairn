// --- fs helpers ---------------------------------------------------------------

fn mkdirs(path: &Path) -> Result<(), Halt> {
    fs::create_dir_all(path).map_err(|err| format!("mkdir {}: {err}", path.display()).into())
}

fn write_text(path: &Path, text: &str) -> Result<(), Halt> {
    fs::write(path, text).map_err(|err| format!("write {}: {err}", path.display()).into())
}

fn read_text(path: &Path) -> Result<String, Halt> {
    fs::read_to_string(path).map_err(|err| format!("read {}: {err}", path.display()).into())
}

fn remove_file(path: &Path) -> Result<(), Halt> {
    match fs::remove_file(path) {
        Err(err) if err.kind() != ErrorKind::NotFound => {
            Err(format!("unlink {}: {err}", path.display()).into())
        }
        _ => Ok(()),
    }
}

fn remove_tree(path: &Path) {
    let _ = fs::remove_dir_all(path);
}

fn remove_db(scratch: &Path) -> Result<(), Halt> {
    for suffix in ["", "-wal", "-shm", "-journal"] {
        remove_file(&scratch.join(format!("{DB_NAME}{suffix}")))?;
    }
    Ok(())
}

fn with_db(
    scratch: &Path,
    work: impl FnOnce(&Connection) -> rusqlite::Result<()>,
) -> Result<(), Halt> {
    let db = scratch.join(DB_NAME);
    Connection::open(&db)
        .and_then(|conn| work(&conn))
        .map_err(|err| format!("sqlite {}: {err}", db.display()).into())
}

