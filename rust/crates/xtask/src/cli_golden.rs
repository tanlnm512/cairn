/// State a mutating leg restores before it runs.
#[derive(Clone, Copy)]
enum Reseed {
    Task(&'static str),
    Wiki,
    HooksFresh,
    HooksInstalled,
    SyncDrift,
    BlastDrift,
    BrokenConcept,
    KnowledgeExtras,
    RestorePinned,
    WorkflowSync,
    MemoryReset,
    CompassReset,
    Registry,
    ReviewDrift,
}

impl Reseed {
    fn keyed(key: &[&str]) -> Option<Self> {
        Some(match key {
            ["task", "claim", "golden-claim"] => Self::Task("golden-claim"),
            ["task", "complete", "golden-complete"] => Self::Task("golden-complete"),
            ["task", "complete", "golden-revise"] => Self::Task("golden-revise"),
            ["task", "drop", "golden-drop"] => Self::Task("golden-drop"),
            ["wiki", "generate"]
            | ["wiki", "generate", "--llm"]
            | ["wiki", "retry"]
            | ["wiki", "enrich", "--all"] => Self::Wiki,
            ["hooks", "install", "--workspace"] => Self::HooksFresh,
            ["hooks", "uninstall", "--workspace"] => Self::HooksInstalled,
            ["sync", "--workspace"] => Self::SyncDrift,
            ["blast"] | ["blast", "--format"] | ["blast", "--base"] => Self::BlastDrift,
            ["validate"] => Self::BrokenConcept,
            ["knowledge", "embed"] => Self::KnowledgeExtras,
            ["knowledge", "rebuild"] | ["knowledge", "ingest"] => Self::RestorePinned,
            ["knowledge", "workflow", "sync"] => Self::WorkflowSync,
            [
                "memory",
                "reflect" | "evolve" | "capture" | "embed" | "batch-critic" | "consolidate",
            ]
            | ["review", "--capture-event"] => Self::MemoryReset,
            ["compass", "generate" | "flow" | "flow-gaps"] => Self::CompassReset,
            ["ask", "--all-repos"] => Self::Registry,
            ["review", "--base" | "--pre-submit"] => Self::ReviewDrift,
            _ => return None,
        })
    }

    /// The 3-word key first, then the 2-word key when the argv runs past it.
    fn for_command(words: &[&str]) -> Option<Self> {
        Self::keyed(&words[..words.len().min(3)]).or_else(|| {
            if words.len() > 2 {
                Self::keyed(&words[..2])
            } else {
                None
            }
        })
    }

    fn apply(self, scratch: &Path) -> Result<(), Halt> {
        match self {
            Self::Task(task_id) => seed_task(scratch, task_id),
            Self::Wiki => seed_wiki(scratch),
            Self::HooksFresh => reset_hooks_workspace(scratch, false),
            Self::HooksInstalled => reset_hooks_workspace(scratch, true),
            Self::SyncDrift => seed_sync_drift(scratch),
            Self::BlastDrift => seed_blast_drift(scratch),
            Self::BrokenConcept => write_seed(scratch, "reports/broken-no-type"),
            Self::KnowledgeExtras => seed_knowledge_extras(scratch),
            Self::RestorePinned => restore_pinned(scratch),
            Self::WorkflowSync => seed_workflow_sync(scratch),
            Self::MemoryReset => seed_memory_reset(scratch),
            Self::CompassReset => seed_compass_reset(scratch),
            Self::Registry => seed_registry(scratch),
            Self::ReviewDrift => seed_review_drift(scratch),
        }
    }
}

fn env_overrides(words: &[&str]) -> &'static [(&'static str, &'static str)] {
    match words.get(..2) {
        Some(["upgrade", "--check"]) => &[("https_proxy", DEAD_PROXY), ("HTTPS_PROXY", DEAD_PROXY)],
        // ANN on draws indeterminate progress segments carrying elapsed seconds with no `%` token.
        Some(["embed", "--limit"]) => &[("CAIRN_ANN_BACKEND", "off")],
        _ => &[],
    }
}

fn stdin_override(words: &[&str]) -> Option<&'static str> {
    match words.get(..3) {
        Some(["memory", "capture", "--session-transcript-stdin"]) => Some(CAPTURE_TRANSCRIPT),
        _ => None,
    }
}

