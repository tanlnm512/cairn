/// Materialize one frozen concept into the scratch bundle.
fn write_seed(scratch: &Path, concept_id: &str) -> Result<(), Halt> {
    let src = seeds_dir().join(format!("{concept_id}.md"));
    if !src.is_file() {
        return Err(format!(
            "missing frozen seed {}; the fixtures are frozen — restore it from history",
            src.display()
        )
        .into());
    }
    let dst = scratch.join(".knowledge").join(format!("{concept_id}.md"));
    if let Some(parent) = dst.parent() {
        mkdirs(parent)?;
    }
    Ok(parity::copy_file(&src, &dst)?)
}

fn prepare_store(scratch: &Path) -> Result<(), Halt> {
    parity::load_pinned_store("self", scratch)?;
    for task_id in GOLDEN_TASKS {
        seed_task(scratch, task_id)?;
    }
    seed_wiki(scratch)?;
    seed_telemetry(scratch)?;
    seed_knowledge_extras(scratch)?;
    seed_memory_extras(scratch)?;
    seed_workflow_sync(scratch)
}

