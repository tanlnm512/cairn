/// Hooks workspace: repo alpha (clean), repo beta (foreign post-commit), and an empty dir.
fn prepare_hooks_workspace(scratch: &Path) -> Result<PathBuf, Halt> {
    let ws = scratch.join("hooks-ws");
    for repo in ["alpha", "beta"] {
        mkdirs(&ws.join(repo).join(".git").join("hooks"))?;
    }
    write_text(
        &ws.join("beta")
            .join(".git")
            .join("hooks")
            .join("post-commit"),
        FOREIGN_HOOK,
    )?;
    mkdirs(&ws.join("empty"))?;
    Ok(ws)
}

/// Restore the hooks workspace to its pre-install or post-install (managed-hook) state.
fn reset_hooks_workspace(scratch: &Path, installed: bool) -> Result<(), Halt> {
    let ws = scratch.join("hooks-ws");
    let hooks = |repo: &str| ws.join(repo).join(".git").join("hooks");
    for repo in ["alpha", "beta"] {
        for name in ["post-commit", "post-checkout"] {
            remove_file(&hooks(repo).join(name))?;
        }
    }
    write_text(&hooks("beta").join("post-commit"), FOREIGN_HOOK)?;
    if !installed {
        return Ok(());
    }
    for repo in ["alpha", "beta"] {
        for (name, template) in [
            ("post-commit", POST_COMMIT_HOOK),
            ("post-checkout", POST_CHECKOUT_HOOK),
        ] {
            let path = hooks(repo).join(name);
            if path.exists() {
                continue;
            }
            write_text(&path, &template.replace("{repo}", repo))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                fs::set_permissions(&path, fs::Permissions::from_mode(0o755))
                    .map_err(|err| format!("chmod {}: {err}", path.display()))?;
            }
        }
    }
    Ok(())
}

