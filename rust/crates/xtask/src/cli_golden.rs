/// Reset leg-created wiki state, then seed a promoted, a failed and a dropped page plus a Notes report.
fn seed_wiki(scratch: &Path) -> Result<(), Halt> {
    let knowledge = scratch.join(".knowledge");
    remove_tree(&knowledge.join("reports"));
    if let Ok(entries) = fs::read_dir(knowledge.join("_tasks")) {
        for entry in entries.flatten() {
            if !entry.file_name().to_string_lossy().starts_with("golden") {
                remove_file(&entry.path())?;
            }
        }
    }
    for task_id in ["golden-page", "golden-failed", "golden-wdrop"] {
        seed_task(scratch, task_id)?;
    }
    write_seed(scratch, "wiki/pages/cairn/overview")?;
    write_seed(scratch, "reports/architecture/corpus")?;
    let manifest = json!({
        "schema": "cairn-wiki-manifest-3",
        "pages": {
            "cairn/overview": wiki_row("overview", "golden-page"),
            "cairn/failed-page": wiki_row("failed-page", "golden-failed"),
            "cairn/dropped-page": wiki_row("dropped-page", "golden-wdrop"),
        },
    });
    let manifest_dir = knowledge.join("_wiki");
    mkdirs(&manifest_dir)?;
    write_text(
        &manifest_dir.join("manifest.json"),
        &format!("{}\n", py_json_pretty(&manifest, true)),
    )
}

