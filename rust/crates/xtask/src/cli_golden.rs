struct Outcome {
    code: i64,
    stdout: String,
    stderr: String,
}

fn drain(pipe: Option<impl Read + Send + 'static>) -> thread::JoinHandle<Vec<u8>> {
    thread::spawn(move || {
        let mut buf = Vec::new();
        if let Some(mut pipe) = pipe {
            let _ = pipe.read_to_end(&mut buf);
        }
        buf
    })
}

/// Decoded text with universal newlines (`\r\n` and `\r` become `\n`).
fn decode(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes)
        .replace("\r\n", "\n")
        .replace('\r', "\n")
}

/// Exit code with signals as negative numbers.
fn status_code(status: ExitStatus) -> i64 {
    #[cfg(unix)]
    {
        use std::os::unix::process::ExitStatusExt;
        if let Some(signal) = status.signal() {
            return -i64::from(signal);
        }
    }
    status.code().map_or(-1, i64::from)
}

fn run_side(
    exe: &Path,
    argv: &[String],
    env: &Env,
    cwd: &Path,
    stdin: Option<&str>,
) -> Result<Outcome, Halt> {
    let fail = |err: std::io::Error| Halt::from(format!("cannot run {}: {err}", exe.display()));
    let mut child = Command::new(exe)
        .args(argv)
        .current_dir(cwd)
        .env_clear()
        .envs(env)
        .stdin(if stdin.is_some() {
            Stdio::piped()
        } else {
            Stdio::inherit()
        })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(fail)?;
    if let (Some(text), Some(mut pipe)) = (stdin, child.stdin.take()) {
        let text = text.to_string();
        thread::spawn(move || {
            let _ = pipe.write_all(text.as_bytes());
        });
    }
    let (stdout, stderr) = (drain(child.stdout.take()), drain(child.stderr.take()));
    let deadline = Instant::now() + CMD_TIMEOUT;
    let status = loop {
        if let Some(status) = child.try_wait().map_err(fail)? {
            break status;
        }
        if Instant::now() >= deadline {
            let _ = child.kill();
            let _ = child.wait();
            return Err(format!(
                "Command {:?} timed out after {} seconds",
                argv,
                CMD_TIMEOUT.as_secs()
            )
            .into());
        }
        thread::sleep(Duration::from_millis(5));
    };
    let joined = |handle: thread::JoinHandle<Vec<u8>>| decode(&handle.join().unwrap_or_default());
    Ok(Outcome {
        code: status_code(status),
        stdout: joined(stdout),
        stderr: joined(stderr),
    })
}

/// Seed, then run one case with its env/stdin/cwd overrides.
fn run_case(cmd: &[String], exe: &Path, env: &Env, scratch: &Path) -> Result<Outcome, Halt> {
    let words: Vec<&str> = cmd.iter().map(String::as_str).collect();
    if let Some(reseed) = Reseed::for_command(&words) {
        reseed.apply(scratch)?;
    }
    let mut env = env.clone();
    for (key, value) in env_overrides(&words) {
        env.insert(key.into(), value.into());
    }
    let root = repo_root();
    // `report` runs from scratch so the repo-dev quality gates render their no-source-root arm.
    let cwd = if words.first() == Some(&"report") {
        scratch
    } else {
        &root
    };
    run_side(exe, cmd, &env, cwd, stdin_override(&words))
}

// --- normalization and diff ------------------------------------------------------

fn normalize(text: &str, rules: &[ScrubRule]) -> String {
    gr::normalize_text(&ANSI_RE.replace_all(text, ""), rules, false, false)
}

/// Scratch-independent identity of one case: its argv with paths scrubbed.
fn case_label(argv: &[String], rules: &[ScrubRule]) -> String {
    argv.iter()
        .map(|arg| normalize(arg, rules))
        .collect::<Vec<_>>()
        .join(" ")
}

/// First divergence between a frozen case and a live run.
fn first_diff(
    expected: &Value,
    actual: &Outcome,
    rules: &[ScrubRule],
) -> Result<Option<String>, Halt> {
    let want_exit = &expected["exit"];
    if want_exit.as_i64() != Some(actual.code) {
        return Ok(Some(format!("exit {want_exit} != {}", actual.code)));
    }
    for (stream, raw) in [("stdout", &actual.stdout), ("stderr", &actual.stderr)] {
        let want = expected[stream].as_str().unwrap_or_default();
        let got = normalize(raw, rules);
        if want == got {
            continue;
        }
        let (wlines, glines) = (gr::py_splitlines(want), gr::py_splitlines(&got));
        if let Some((i, (a, b))) = wlines
            .iter()
            .zip(&glines)
            .enumerate()
            .find(|(_, (a, b))| a != b)
        {
            return Ok(Some(format!(
                "{stream} line {i}: {} != {}",
                gr::py_str_repr(a),
                gr::py_str_repr(b)
            )));
        }
        let (side, extra) = if wlines.len() > glines.len() {
            ("fixture", &wlines[glines.len()..])
        } else {
            ("rust", &glines[wlines.len()..])
        };
        let Some(first) = extra.first() else {
            return Err(
                format!("{stream}: fixture and rust differ only in line terminators").into(),
            );
        };
        return Ok(Some(format!(
            "{stream}: {side} has {} extra line(s): {}",
            extra.len(),
            gr::py_str_repr(first)
        )));
    }
    Ok(None)
}

